/* =====================================================================
 * Kudbee Leaderboard — worker/build-single.mjs
 * Joins the Worker and its shared modules into ONE file (dist/worker.single.js)
 * that can be pasted into the Cloudflare dashboard's code editor, so the Worker
 * can be deployed from a phone with no command line. Each module keeps its own
 * scope (wrapped in a function), so names that repeat across modules (authError
 * is in both auth.js and algo-auth.js) cannot collide. The output is checked by
 * test/single-file.test.js, which fails if dist/ has drifted from the source.
 *
 *   node worker/build-single.mjs          write dist/worker.single.js
 * ===================================================================== */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');                  // leaderboard/
export const OUT = path.join(HERE, 'dist', 'worker.single.js');

// Dependency order: every module comes after the ones it imports from.
const MODULES = [
  { file: 'shared/algo-auth.js', ns: 'algoAuth' },
  { file: 'shared/auth.js', ns: 'auth' },
  { file: 'shared/core.js', ns: 'core' },
  { file: 'shared/http.js', ns: 'http' },
  { file: 'worker/store-d1.js', ns: 'storeD1' },
];
const ENTRY = 'worker/worker.js';

const rel = (p) => path.relative(ROOT, p) || p;
const nsFor = Object.fromEntries(MODULES.map((m) => [path.basename(m.file), m.ns]));

function importsOf(src, file) {
  const out = [];
  for (const m of src.matchAll(/^import \{([^}]*)\} from '([^']+)';?[ \t]*$/gm)) {
    const from = path.basename(m[2]);
    if (!nsFor[from]) throw new Error(`${file}: import from unknown module ${m[2]}`);
    out.push({ line: m[0], names: m[1].split(',').map((s) => s.trim()).filter(Boolean), ns: nsFor[from] });
  }
  return out;
}

function exportsOf(src) {
  return [...src.matchAll(/^export (?:async )?(?:function|const|let|class) (\w+)/gm)].map((m) => m[1]);
}

function wrapModule(file, ns) {
  const src = readFileSync(path.join(ROOT, file), 'utf8');
  if (/^export default/m.test(src) || /^export \{/m.test(src) || /import\.meta/.test(src)) {
    throw new Error(`${file}: unsupported form for the single-file build`);
  }
  let body = src;
  const imports = importsOf(src, file);
  for (const imp of imports) {
    body = body.replace(imp.line, `const { ${imp.names.join(', ')} } = ${imp.ns};`);
  }
  body = body.replace(/^export (?=(?:async )?(?:function|const|let|class) )/gm, '');
  const names = exportsOf(src);
  return `// ---- ${rel(path.join(ROOT, file))} ----\nconst ${ns} = (() => {\n${body}\nreturn { ${names.join(', ')} };\n})();\n`;
}

export function buildSingle() {
  const parts = [
    '// Kudbee Leaderboard — Cloudflare Worker, one file.',
    '// GENERATED by worker/build-single.mjs from the sources in shared/ and worker/. Edit those, then rebuild.',
    '',
  ];
  for (const m of MODULES) parts.push(wrapModule(m.file, m.ns));

  const entry = readFileSync(path.join(ROOT, ENTRY), 'utf8');
  for (const imp of importsOf(entry, ENTRY)) {
    parts.push(`const { ${imp.names.join(', ')} } = ${imp.ns};`);
  }
  parts.push(entry.replace(/^import .*$/gm, ''));
  return parts.join('\n').replace(/\n{3,}/g, '\n\n');
}

// `node worker/build-single.mjs` writes the file; importing this module does not.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  mkdirSync(path.dirname(OUT), { recursive: true });
  writeFileSync(OUT, buildSingle());
  console.log(`wrote ${rel(OUT)}`);
}
