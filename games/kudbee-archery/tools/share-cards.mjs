// Renders the link-preview cards for Kudbee Archery's share links and writes their landing pages. Every share from
// the game links to s/<slug>/ (a world, a cup, the daily, the tour or a trophy); that page's og:image is the same
// brag card the game paints (KAR.Share.card), with the challenge instead of a score, so a pasted link unfurls with
// the right picture. The page sends people straight on to the game.
//   node games/kudbee-archery/tools/share-cards.mjs   (writes assets/og/archery/<slug>.jpg + games/kudbee-archery/s/<slug>/index.html)
// Bump VER when the cards change: X / iMessage / Facebook cache a card for days.
import http from 'node:http';
import { readFileSync, existsSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, extname, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const VER = 1;
const HERE = dirname(fileURLToPath(import.meta.url)), ROOT = resolve(HERE, '..', '..', '..'), GAME = resolve(HERE, '..');
const { chromium } = createRequire(resolve(HERE, '..', 'eval', 'x.js'))('playwright');
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.woff2': 'font/woff2', '.jpg': 'image/jpeg', '.png': 'image/png' };
const server = http.createServer((q, s) => { let p = join(ROOT, decodeURIComponent(q.url.split('?')[0])); if (existsSync(p) && statSync(p).isDirectory()) p = join(p, 'index.html'); if (!p.startsWith(ROOT) || !existsSync(p)) { s.writeHead(404); return s.end(); } s.writeHead(200, { 'content-type': MIME[extname(p)] || 'application/octet-stream' }); s.end(readFileSync(p)); });
await new Promise(r => server.listen(0, r));
const b = await chromium.launch(existsSync('/opt/pw-browsers/chromium') ? { executablePath: '/opt/pw-browsers/chromium' } : {});
const page = await b.newPage({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
await page.goto(`http://localhost:${server.address().port}/games/kudbee-archery/index.html`);
await page.waitForFunction(() => window.KARGame); await page.evaluate(() => document.fonts.ready);
const cards = await page.evaluate(() => KAR.Share.SLUGS.map(slug => {
  const info = KAR.Share.generic(slug), cv = KAR.Share.card(info);
  return { slug, info, url: KAR.Share.url(slug), game: KAR.Share.url(''), site: KAR.Share.SITE, jpg: cv.toDataURL('image/jpeg', 0.86) };
}));
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const cap = s => String(s).toLowerCase().replace(/(^|[\s(\-·])([a-z])/g, (m, a, c) => a + c.toUpperCase());
mkdirSync(resolve(ROOT, 'assets', 'og', 'archery'), { recursive: true });
for (const c of cards) {
  const img = resolve(ROOT, 'assets', 'og', 'archery', c.slug + '.jpg');
  writeFileSync(img, Buffer.from(c.jpg.split(',')[1], 'base64'));
  const I = c.info, imgURL = `${c.site}/assets/og/archery/${c.slug}.jpg?v=${VER}`;
  const title = `${cap(I.ribbon)}: ${cap(I.big)} — Kudbee Archery`;
  const desc = `${cap(I.line1)}. ${cap(I.line2)} Kudbee Archery: read the wind, hold your breath, hit the gold — free in your browser, built for phones.`.replace(/\?\. /, '? ').replace(/\.\. /, '. ');
  const alt = `Kudbee Archery share card: ${cap(I.ribbon)} — ${cap(I.big)}`;
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(desc)}">
<meta name="robots" content="noindex, follow">
<!-- generated by games/kudbee-archery/tools/share-cards.mjs: a share link's landing page (its card, then on to the game) -->
<link rel="canonical" href="${c.url}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Kudbee">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:url" content="${c.url}">
<meta property="og:image" content="${imgURL}">
<meta property="og:image:secure_url" content="${imgURL}">
<meta property="og:image:type" content="image/jpeg">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="${esc(alt)}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(title)}">
<meta name="twitter:description" content="${esc(desc)}">
<meta name="twitter:image" content="${imgURL}">
<meta name="twitter:image:alt" content="${esc(alt)}">
<meta name="theme-color" content="#1d2a3a">
<script>location.replace('../../index.html');</script>
<style>
  html, body { margin: 0; min-height: 100%; background: #1d2a3a; color: #fff; font: 600 16px/1.4 system-ui, sans-serif; }
  main { max-width: 760px; margin: 0 auto; padding: 24px 16px; text-align: center; }
  img { width: 100%; height: auto; border-radius: 14px; border: 3px solid #fff; display: block; }
  a.play { display: inline-block; margin-top: 18px; padding: 14px 28px; border-radius: 14px; background: #53bd3c; color: #fff; text-decoration: none; font-size: 20px; border: 3px solid #1d2a3a; box-shadow: 0 4px 0 #2f8a2a; }
</style>
</head>
<body>
<main>
  <img src="/assets/og/archery/${c.slug}.jpg?v=${VER}" width="1200" height="630" alt="${esc(alt)}">
  <a class="play" href="../../index.html">Play Kudbee Archery</a>
</main>
</body>
</html>
`;
  const dir = resolve(GAME, 's', c.slug); mkdirSync(dir, { recursive: true }); writeFileSync(join(dir, 'index.html'), html);
  console.log('wrote', c.slug, Math.round(c.jpg.length * 0.75 / 1024) + 'KB');
}
await b.close(); server.close();
