// Renders the link-preview cards for Kudbee Abyss and writes their landing pages. Every share from the game links to
// s/<slug>/ (an ending, or "progress"); that page's og:image is the same card the game paints (ABY.Share.card) without the
// personal count, so a pasted link unfurls with the right picture. The page sends people straight on to the game.
// The game's own page card (assets/og/abyss.jpg) is rendered here too.
//   node games/kudbee-abyss/tools/share-cards.mjs   (writes assets/og/abyss/<slug>.jpg, assets/og/abyss.jpg, games/kudbee-abyss/s/<slug>/index.html)
// Bump VER (and the ?v= in index.html's og:image) when the cards change: X / iMessage / Facebook cache a card for days.
import http from 'node:http';
import { readFileSync, existsSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, extname, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const VER = 1;
const HERE = dirname(fileURLToPath(import.meta.url)), ROOT = resolve(HERE, '..', '..', '..'), GAME = resolve(HERE, '..');
const { chromium } = createRequire(resolve(ROOT, 'package.json'))('playwright');
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.webp': 'image/webp', '.jpg': 'image/jpeg', '.png': 'image/png' };
const server = http.createServer((q, s) => { let p = join(ROOT, decodeURIComponent(q.url.split('?')[0])); if (existsSync(p) && statSync(p).isDirectory()) p = join(p, 'index.html'); if (!p.startsWith(ROOT) || !existsSync(p)) { s.writeHead(404); return s.end(); } s.writeHead(200, { 'content-type': MIME[extname(p)] || 'application/octet-stream' }); s.end(readFileSync(p)); });
await new Promise(r => server.listen(0, r));
const b = await chromium.launch(existsSync('/opt/pw-browsers/chromium') ? { executablePath: '/opt/pw-browsers/chromium' } : {});
const page = await b.newPage({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
await page.route('https://cdnjs.cloudflare.com/**', r => r.abort());          // the cards are 2D: the 3D library is not needed
await page.route('https://fonts.*/**', r => r.abort());
await page.goto(`http://localhost:${server.address().port}/games/kudbee-abyss/index.html`);
await page.waitForFunction(() => window.ABY && ABY.Art && ABY.Art.queen && ABY.Art.queen.complete && ABY.Art.city.complete && ABY.Art.corrupt.complete && ABY.Art.stairs.complete && ABY.Art.stairs.naturalWidth, null, { timeout: 20000 });
await page.evaluate(() => document.fonts.ready);
const cards = await page.evaluate(() => ABY.Share.SLUGS.concat(['']).map(slug => {
  const info = ABY.Share.generic(slug || 'game'), cv = ABY.Share.card(info);
  return { slug, info, url: ABY.Share.url(slug), site: ABY.Share.SITE, jpg: cv.toDataURL('image/jpeg', 0.88) };
}));
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const cap = s => String(s).toLowerCase().replace(/(^|[\s(\-])([a-z])/g, (m, a, c) => a + c.toUpperCase()).replace(/’S/g, '’s');
mkdirSync(resolve(ROOT, 'assets', 'og', 'abyss'), { recursive: true });
for (const c of cards) {
  const buf = Buffer.from(c.jpg.split(',')[1], 'base64');
  if (!c.slug) { writeFileSync(resolve(ROOT, 'assets', 'og', 'abyss.jpg'), buf); console.log('wrote assets/og/abyss.jpg', Math.round(buf.length / 1024) + 'KB'); continue; }
  writeFileSync(resolve(ROOT, 'assets', 'og', 'abyss', c.slug + '.jpg'), buf);
  const I = c.info, imgURL = `${c.site}/assets/og/abyss/${c.slug}.jpg?v=${VER}`;
  const title = c.slug === 'progress' ? 'Find all 5 endings — Kudbee Abyss' : `${I.title} — Kudbee Abyss`;
  const desc = c.slug === 'progress' ? 'A story told through a haunted phone. Text the Queen, play the Song of Recall on the Echo Flute and find all five endings. Free in your browser, built for phones.' : `${cap(I.line1)}. A story told through a haunted phone: text the Queen, play the Song of Recall, find all five endings. Free in your browser, built for phones.`;
  const alt = `Kudbee Abyss share card: ${I.title}`;
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(desc)}">
<meta name="robots" content="noindex, follow">
<!-- generated by games/kudbee-abyss/tools/share-cards.mjs: a share link's landing page (its card, then on to the game) -->
<link rel="canonical" href="${c.url}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Kudbee">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:url" content="${c.url}">
<meta property="og:image" content="${imgURL}">
<meta property="og:image:secure_url" content="${imgURL}">
<meta property="og:image:type" content="image/jpeg">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="${esc(alt)}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(title)}">
<meta name="twitter:description" content="${esc(desc)}">
<meta name="twitter:image" content="${imgURL}">
<meta name="twitter:image:alt" content="${esc(alt)}">
<meta name="theme-color" content="#05031a">
<script>location.replace('../../index.html');</script>
<style>
  html, body { margin: 0; min-height: 100%; background: #05031a; color: #fff; font: 600 16px/1.4 system-ui, sans-serif; }
  main { max-width: 760px; margin: 0 auto; padding: 24px 16px; text-align: center; }
  img { width: 100%; height: auto; border-radius: 14px; border: 1px solid #5b3fa0; display: block; }
  a.play { display: inline-block; margin-top: 18px; padding: 14px 28px; border-radius: 999px; background: linear-gradient(120deg, #39e6ff, #c46bff); color: #05031a; text-decoration: none; font-size: 20px; font-weight: 700; }
</style>
</head>
<body>
<main>
  <img src="/assets/og/abyss/${c.slug}.jpg?v=${VER}" width="1200" height="630" alt="${esc(alt)}">
  <a class="play" href="../../index.html">Play Kudbee Abyss</a>
</main>
</body>
</html>
`;
  const dir = resolve(GAME, 's', c.slug); mkdirSync(dir, { recursive: true }); writeFileSync(join(dir, 'index.html'), html);
  console.log('wrote', c.slug, Math.round(buf.length / 1024) + 'KB');
}
await b.close(); server.close();
